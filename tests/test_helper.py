def load(name, rel):
    loader = importlib.machinery.SourceFileLoader(name, str(ROOT / rel))
    spec = importlib.util.spec_from_loader(name, loader)
    mod = importlib.util.module_from_spec(spec)
    loader.exec_module(mod)
    return mod


helper = load("azurevpn_helper", "libexec/azurevpn-helper")
shim = load("azurevpn_sudo", "libexec/azurevpn-sudo")

UID = 4242
SOCK = f"/run/user/{UID}/openp2s/mgmt.sock"
KEY = "-----BEGIN OpenVPN Static key V1-----\n0123456789abcdef0123456789abcdef\n-----END OpenVPN Static key V1-----"


def good_config(**over):
    """Config in the shape openp2s 0.2.0 generates (management credentials)."""
    parts = {
        "head": "# Generated by OpenP2S. Do not edit\nclient\ndev tun\nproto tcp-client\n\n"
                "remote gw.example.invalid 443\nnobind\nresolv-retry infinite\nremote-cert-tls server\n"
                "verify-x509-name *.vpn.example.invalid name\ncipher AES-256-GCM\n"
                "data-ciphers AES-256-GCM\ndata-ciphers-fallback AES-256-GCM\nauth SHA256\n"
                "reneg-sec 0\nauth-nocache\nca /etc/ssl/certs/ca-certificates.crt\n",
        "mgmt": f"auth-user-pass\nmanagement {SOCK} unix\nmanagement-client\n"
                "management-query-passwords\nmanagement-hold\n",
        "tail": f"verb 3\nkey-direction 1\n<tls-auth>\n{KEY}\n</tls-auth>\n",
    }
    parts.update(over)
    return parts["head"] + parts["mgmt"] + parts.get("extra", "") + parts["tail"]


def reject(testcase, text):
    with testcase.assertRaises(helper.HelperError):
        helper.validate_openvpn_config(text, UID)


class GoodConfig(unittest.TestCase):
    def test_generated_shape_is_accepted_and_rebuilt(self):
        out = helper.validate_openvpn_config(good_config(), UID)
        self.assertIn("remote gw.example.invalid 443", out)
        self.assertNotIn("#", out.split("<tls-auth>")[0])  # comments are dropped
        self.assertTrue(out.endswith("</tls-auth>\n"))

    def test_inline_ca_and_compat_accepted(self):
        text = good_config(extra="experimental-azure-compat\n").replace(
            "ca /etc/ssl/certs/ca-certificates.crt\n",
            "<ca>\n-----BEGIN CERTIFICATE-----\nMIIDdzCCAl+gAwIBAgIE\n-----END CERTIFICATE-----\n</ca>\n")
        helper.validate_openvpn_config(text, UID)


