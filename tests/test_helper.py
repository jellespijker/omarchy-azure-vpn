class DnsRequests(unittest.TestCase):
    def test_valid_requests(self):
        self.assertEqual(helper.parse_dns_request("dns-servers", "tun0\n10.0.0.4\nfd00::1\n"),
                         ["dns", "tun0", "10.0.0.4", "fd00::1"])
        self.assertEqual(helper.parse_dns_request("dns-domains", "tun1\ncorp.example.invalid\n~vpn.example.invalid\n~.\n"),
                         ["domain", "tun1", "corp.example.invalid", "~vpn.example.invalid", "~."])
        self.assertEqual(helper.parse_dns_request("dns-default-route", "tun0\n"), ["default-route", "tun0", "no"])
        self.assertEqual(helper.parse_dns_request("dns-revert", "tun0\n"), ["revert", "tun0"])

    def test_bad_interfaces_rejected(self):
        for iface in ("eth0", "wlan0", "lo", "tun", "tun99999", "tun0; reboot", "-h", "../tun0",
                      "tun0 tun1", "tun0\x00", "TUN0", "tap0", "tun0/../eth0", ""):
            with self.subTest(iface=iface):
                with self.assertRaises(helper.HelperError):
                    helper.parse_dns_request("dns-revert", iface + "\n")

    def test_bad_dns_servers_rejected(self):
        for v in ("not-an-ip", "10.0.0.1 --set-dns", "-h", "10.0.0.256", "example.com",
                  "10.0.0.1/24", "1.2.3", "::g", "0x7f000001", ""):
            with self.subTest(v=v):
                with self.assertRaises(helper.HelperError):
                    helper.parse_dns_request("dns-servers", f"tun0\n{v}\n")
        with self.assertRaises(helper.HelperError):
            helper.parse_dns_request("dns-servers", "tun0\n")
        with self.assertRaises(helper.HelperError):
            helper.parse_dns_request("dns-servers", "tun0\n" + "10.0.0.1\n" * 9)

    def test_bad_domains_rejected(self):
        for v in ("-h", "--flush-caches", "a b", "a;b", "$(id)", "../x", "~", "..", "a" * 64 + ".com", "x/y"):
            with self.subTest(v=v):
                with self.assertRaises(helper.HelperError):
                    helper.parse_dns_request("dns-domains", f"tun0\n{v}\n")

    def test_extra_input_and_unknown_kinds_rejected(self):
        with self.assertRaises(helper.HelperError):
            helper.parse_dns_request("dns-revert", "tun0\nextra\n")
        with self.assertRaises(helper.HelperError):
            helper.parse_dns_request("dns-default-route", "tun0\nyes\n")
        with self.assertRaises(helper.HelperError):
            helper.parse_dns_request("status", "tun0\n")
        with self.assertRaises(helper.HelperError):
            helper.parse_dns_request("dns-revert", "")
        with self.assertRaises(helper.HelperError):
            helper.parse_dns_request("dns-servers", "tun0\n" + "x" * 9000)


class FilesystemTrust(unittest.TestCase):
    def test_root_owned_chain_rejects_user_owned_and_writable_and_symlinks(self):
        with tempfile.TemporaryDirectory() as td:
            f = Path(td) / "bin"
            f.write_text("x")
            me = os.getuid()
            # Pretend "root" is the current user so the chain can be built in a temp dir.
            if me != 0:
                with self.assertRaises(helper.HelperError):  # real root uid 0 != me
                    helper.assert_root_owned_chain(str(f))
            os.chmod(td, 0o755)
            os.chmod(f, 0o755)
            helper.assert_root_owned_chain(str(f), root_uid=me, lstat=_skip_above(td))
            os.chmod(f, 0o777)
            with self.assertRaises(helper.HelperError):
                helper.assert_root_owned_chain(str(f), root_uid=me, lstat=_skip_above(td))
            os.chmod(f, 0o755)
            link = Path(td) / "link"
            link.symlink_to(f)
            with self.assertRaises(helper.HelperError):
                helper.assert_root_owned_chain(str(link), root_uid=me, lstat=_skip_above(td))

    def test_traversal_and_relative_paths_rejected(self):
        for p in ("relative/path", "/usr/local/lib/../../../etc/shadow", "/a/../b"):
            with self.subTest(p=p):
                with self.assertRaises(helper.HelperError):
                    helper.assert_root_owned_chain(p)

    def test_read_user_config_rejects_symlink_foreign_owner_and_oversize(self):
        with tempfile.TemporaryDirectory() as td:
            real = Path(td) / "real.conf"
            real.write_text(good_config())
            me = os.getuid()
            self.assertIn("client", helper.read_user_config(me, str(real)))
            link = Path(td) / "link.conf"
            link.symlink_to(real)
            with self.assertRaises(helper.HelperError):
                helper.read_user_config(me, str(link))          # symlink
            with self.assertRaises(helper.HelperError):
                helper.read_user_config(me + 1, str(real))      # not owned by claimed caller
            big = Path(td) / "big.conf"
            big.write_text("#" * (helper.MAX_CONFIG_BYTES + 10))
            with self.assertRaises(helper.HelperError):
                helper.read_user_config(me, str(big))
            hard = Path(td) / "hard.conf"
            os.link(real, hard)
            with self.assertRaises(helper.HelperError):
                helper.read_user_config(me, str(hard))          # hard link (nlink 2)

    def test_private_config_written_0600_with_validated_content_only(self):
        with tempfile.TemporaryDirectory() as td:
            run = Path(td) / "azurevpn"
            clean = helper.validate_openvpn_config(good_config(extra="# up /tmp/x\n"), UID)
            dest = helper.write_private_config(clean, UID, run_dir=str(run))
            self.assertEqual(stat.S_IMODE(os.stat(dest).st_mode), 0o600)
            self.assertEqual(stat.S_IMODE(os.stat(run).st_mode), 0o700)
            self.assertNotIn("/tmp/x", Path(dest).read_text())
            helper.write_private_config(clean, UID, run_dir=str(run))  # overwrite is fine
            os.chmod(run, 0o755)
            with self.assertRaises(helper.HelperError):
                helper.write_private_config(clean, UID, run_dir=str(run))


def _skip_above(top):
    """lstat that reports directories above `top` as fine (root-owned stand-ins)."""
    real = os.lstat
    top = os.path.realpath(top)

    def fake(path):
        st = real(path)
        if not os.path.realpath(path).startswith(top):
            class S:  # pragma: no cover - ownership stand-in for system dirs
                st_mode = stat.S_IFDIR | 0o755
                st_uid = os.getuid()
            return S
        return st
    return fake


class SudoShim(unittest.TestCase):
    def test_translates_only_known_command_lines(self):
        self.assertEqual(shim.translate(["--", shim.OPENVPN_BIN, "--config", f"/run/user/{UID}/openp2s/openvpn.conf"], UID),
                         ("connect", ""))
        self.assertEqual(shim.translate(["--", "/usr/bin/resolvectl", "dns", "tun0", "10.0.0.4"], UID),
                         ("dns-servers", "tun0\n10.0.0.4\n"))
        self.assertEqual(shim.translate(["--", "/usr/bin/resolvectl", "default-route", "tun0", "no"], UID),
                         ("dns-default-route", "tun0\n"))
        self.assertEqual(shim.translate(["--", "/usr/bin/resolvectl", "revert", "tun0"], UID), ("dns-revert", "tun0\n"))

    def test_refuses_everything_else(self):
        bad = [
            ["--", shim.OPENVPN_BIN, "--config", "/tmp/evil.conf"],
            ["--", shim.OPENVPN_BIN, "--script-security", "2", "--up", "/tmp/x"],
            ["--", shim.OPENVPN_BIN, "--config", f"/run/user/{UID}/openp2s/openvpn.conf", "--up", "/x"],
            ["--", "/bin/sh", "-c", "id"], ["--", "id"], [], ["--"],
            ["--", "/usr/bin/resolvectl", "default-route", "tun0", "yes"],
            ["--", "/usr/bin/resolvectl", "dns"], ["--", "/usr/bin/resolvectl", "flush-caches"],
        ]
        for argv in bad:
            with self.subTest(argv=argv):
                with self.assertRaises(ValueError):
                    shim.translate(argv, UID)


